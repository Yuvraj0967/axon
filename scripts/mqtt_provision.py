"""Provision the MQTT broker for AXON Verify.

Generates a private CA, a server certificate, an ingest-worker certificate and
one client certificate per registered device, then writes a Mosquitto ACL that
binds each device identity to exactly one tenant prefix::

    axon/v1/{org_id}/{site_id}/{device_id}/+

The broker enforces the boundary: a device physically cannot publish outside its
own organisation's topic tree, because its certificate identity is the ACL
subject. The application then re-checks the same binding on every message, so a
compromised broker is not sufficient on its own.

Usage::

    python scripts/mqtt_provision.py --org org_abc --site sit_xyz \\
        --device plant1-gw-01 --device plant1-gw-02

Writes into ``docker/mqtt/`` by default. Private keys stay on this machine and
are never committed (``docker/mqtt/certs`` is gitignored).
"""
from __future__ import annotations

import argparse
import datetime as dt
import ipaddress
import os
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = PROJECT_ROOT / "docker" / "mqtt"

MOSQUITTO_CONF = """# AXON Verify — TLS-only MQTT broker, generated by scripts/mqtt_provision.py
listener 8883
cafile   /mosquitto/certs/ca.crt
certfile /mosquitto/certs/server.crt
keyfile  /mosquitto/certs/server.key
require_certificate true
use_identity_as_username true
allow_anonymous false
acl_file /mosquitto/config/acl
persistence true
persistence_location /mosquitto/data/
log_dest stdout
log_type error
log_type warning
log_type notice
"""

INGEST_ACL = """# The verification worker reads every tenant topic; it publishes to none.
user axon-ingest
topic read axon/v1/#
"""


def _name(common_name: str, organisation: str = "AXON Verify") -> x509.Name:
    return x509.Name([
        x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        x509.NameAttribute(NameOID.ORGANIZATION_NAME, organisation),
    ])


def _write(path: Path, data: bytes, mode: int = 0o644) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    os.chmod(path, mode)
    return path


def _pem_certificate(certificate: x509.Certificate) -> bytes:
    return certificate.public_bytes(serialization.Encoding.PEM)


def _pem_key(key: ec.EllipticCurvePrivateKey) -> bytes:
    return key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )


def _issue(subject: x509.Name, issuer_key, issuer_name: x509.Name, public_key,
           *, san: list[x509.GeneralName] | None = None,
           client_auth: bool = False, days: int = 825) -> x509.Certificate:
    now = dt.datetime.now(dt.timezone.utc)
    builder = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(issuer_name)
        .public_key(public_key)
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - dt.timedelta(minutes=5))
        .not_valid_after(now + dt.timedelta(days=days))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(x509.KeyUsage(
            digital_signature=True, content_commitment=False,
            key_encipherment=False, data_encipherment=False,
            key_agreement=False, key_cert_sign=False, crl_sign=False,
            encipher_only=False, decipher_only=False), critical=True)
        .add_extension(x509.ExtendedKeyUsage(
            [x509.oid.ExtendedKeyUsageOID.SERVER_AUTH if not client_auth
             else x509.oid.ExtendedKeyUsageOID.CLIENT_AUTH]), critical=False)
    )
    if san:
        builder = builder.add_extension(x509.SubjectAlternativeName(san), critical=False)
    return builder.sign(issuer_key, hashes.SHA256())


def generate_ca() -> tuple[ec.EllipticCurvePrivateKey, x509.Certificate]:
    key = ec.generate_private_key(ec.SECP256R1())
    now = dt.datetime.now(dt.timezone.utc)
    name = _name("AXON Verify MQTT Local CA")
    certificate = (
        x509.CertificateBuilder()
        .subject_name(name).issuer_name(name).public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - dt.timedelta(minutes=5))
        .not_valid_after(now + dt.timedelta(days=3650))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(x509.KeyUsage(
            digital_signature=True, content_commitment=False, key_encipherment=False,
            data_encipherment=False, key_agreement=False, key_cert_sign=True,
            crl_sign=True, encipher_only=False, decipher_only=False), critical=True)
        .sign(key, hashes.SHA256()))
    return key, certificate


def provision(org_id: str, site_id: str, devices: list[str], out: Path,
              host: str = "localhost") -> dict:
    certs = out / "certs"
    config = out / "config"
    ca_key, ca_cert = generate_ca()

    _write(certs / "ca.crt", _pem_certificate(ca_cert))
    _write(certs / "ca.key", _pem_key(ca_key), mode=0o600)

    # Server certificate for the broker itself.
    server_key = ec.generate_private_key(ec.SECP256R1())
    server_cert = _issue(
        _name(f"{host}"), ca_key, ca_cert.subject, server_key.public_key(),
        san=[x509.DNSName(host), x509.DNSName("localhost"),
             x509.IPAddress(ipaddress.ip_address("127.0.0.1"))])
    _write(certs / "server.crt", _pem_certificate(server_cert))
    _write(certs / "server.key", _pem_key(server_key), mode=0o600)

    # Ingest worker identity: read-only across the whole topic tree.
    ingest_key = ec.generate_private_key(ec.SECP256R1())
    ingest_cert = _issue(_name("axon-ingest"), ca_key, ca_cert.subject,
                         ingest_key.public_key(), client_auth=True)
    _write(certs / "ingest.crt", _pem_certificate(ingest_cert))
    _write(certs / "ingest.key", _pem_key(ingest_key), mode=0o600)

    # One identity per device, bound to its tenant prefix by the ACL.
    acl_lines = [INGEST_ACL]
    fingerprints = {}
    for device in devices:
        key = ec.generate_private_key(ec.SECP256R1())
        common_name = f"axon:{org_id}/{site_id}/{device}"
        certificate = _issue(_name(common_name), ca_key, ca_cert.subject,
                             key.public_key(), client_auth=True)
        _write(certs / f"{device}.crt", _pem_certificate(certificate))
        _write(certs / f"{device}.key", _pem_key(key), mode=0o600)
        fingerprints[device] = certificate.fingerprint(hashes.SHA256()).hex()
        acl_lines.append(f"""
# device {device} — identity {common_name}
user {common_name}
topic readwrite axon/v1/{org_id}/{site_id}/{device}/+
topic read axon/v1/{org_id}/{site_id}/{device}/+
""")

    _write(config / "acl", ("\n".join(acl_lines)).encode("utf-8"))
    _write(config / "mosquitto.conf", MOSQUITTO_CONF.encode("utf-8"))
    (out / "data").mkdir(parents=True, exist_ok=True)
    return {
        "org_id": org_id, "site_id": site_id,
        "devices": {device: {"common_name": f"axon:{org_id}/{site_id}/{device}",
                             "sha256_fingerprint": fingerprints[device]}
                    for device in devices},
        "out": str(out),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--org", required=True, help="organisation id")
    parser.add_argument("--site", required=True, help="site id")
    parser.add_argument("--device", action="append", required=True,
                        help="device key; repeat for each device")
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--host", default="localhost",
                        help="broker hostname for the server certificate SAN")
    args = parser.parse_args(argv)

    report = provision(args.org, args.site, args.device, Path(args.out), args.host)
    print(f"provisioned MQTT mTLS material in {report['out']}")
    for device, details in report["devices"].items():
        print(f"  {device:24s} CN={details['common_name']}")
        print(f"  {'':24s} sha256={details['sha256_fingerprint'][:32]}…")
    print("\nnext: docker compose -f docker-compose.mqtt.yml up -d mosquitto")
    return 0


if __name__ == "__main__":  # pragma: no cover - operator tool
    raise SystemExit(main())
